"""Test agent: builds a regression test for the patch.

Order of preference:
 1. Template test for rule-based fixes (counts the offending pattern before/after).
 2. Model-written pytest test (screened, then run only inside the sandbox).
 3. Syntax-validity test (weak: it only proves the patched file parses).
"""
from __future__ import annotations

import ast

from ..tools.llm_client import LLMError
from ..tools.secrets import redact
from .context import Deps, file_map, window

TEST_PATH = "test_devpilot_regression.py"
FORBIDDEN_IMPORTS = {"os", "subprocess", "socket", "shutil", "requests", "httpx", "urllib", "http", "ctypes",
                     "multiprocessing", "pty", "signal", "importlib", "pathlib", "builtins", "sys"}
FORBIDDEN_CALLS = {"eval", "exec", "open", "__import__", "compile", "input"}


def screen_test_code(code: str) -> str | None:
    """Defence in depth only; the sandbox is the real boundary. Returns a problem or None."""
    if len(code) > 8000:
        return "test is too long"
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        return f"test has a syntax error: {exc.msg}"
    if not any(isinstance(n, ast.FunctionDef) and n.name.startswith("test_") for n in ast.walk(tree)):
        return "no test_ functions found"
    for node in ast.walk(tree):
        names = []
        if isinstance(node, ast.Import):
            names = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom) and node.module:
            names = [node.module.split(".")[0]]
        if set(names) & FORBIDDEN_IMPORTS:
            return f"forbidden import: {sorted(set(names) & FORBIDDEN_IMPORTS)[0]}"
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in FORBIDDEN_CALLS:
            return f"forbidden call: {node.func.id}"
    return None


def _count_bare_except(src: str) -> int:
    return sum(isinstance(n, ast.ExceptHandler) and n.type is None for n in ast.walk(ast.parse(src)))


def _count_none_compare(src: str) -> int:
    n = 0
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Compare):
            for op, comp in zip(node.ops, node.comparators):
                if isinstance(op, (ast.Eq, ast.NotEq)) and isinstance(comp, ast.Constant) and comp.value is None:
                    n += 1
    return n


_TEMPLATE = '''"""Generated by DevPilot (rule-based). Verifies that the flagged pattern was removed. It does NOT test behaviour."""
import ast
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "repo" / {path!r}


def _count(src):
{counter}


def test_flagged_pattern_removed():
    assert _count(TARGET.read_text(encoding="utf-8")) <= {limit}
'''
_COUNTERS = {
    "devpilot.bare-except": "    return sum(isinstance(n, ast.ExceptHandler) and n.type is None for n in ast.walk(ast.parse(src)))",
    "E711": ("    return sum(isinstance(op, (ast.Eq, ast.NotEq)) and isinstance(c, ast.Constant) and c.value is None\n"
             "               for n in ast.walk(ast.parse(src)) if isinstance(n, ast.Compare)\n"
             "               for op, c in zip(n.ops, n.comparators))"),
}
_SYNTAX = '''"""Generated by DevPilot. Weak check: the patched file must parse."""
import ast
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "repo" / {path!r}


def test_patched_file_parses():
    ast.parse(TARGET.read_text(encoding="utf-8"))
'''


async def run(state: dict, deps: Deps) -> dict:
    proposal = state["proposal"]
    finding = next(f for f in state["findings"] if f["id"] == proposal["finding_id"])
    path, files = proposal["file"], file_map(state)
    original = files[path]
    rule = finding["rule_id"]

    if proposal["source"] == "rule" and rule in _COUNTERS:
        counter = _count_bare_except if rule == "devpilot.bare-except" else _count_none_compare
        code = _TEMPLATE.format(path=path, counter=_COUNTERS[rule], limit=counter(original) - 1)
        deps.emit("generate_tests", "done", "Generated a pattern-removal test from a template.", "rule")
        return {"test": {"path": TEST_PATH, "code": code, "kind": "pattern", "source": "template",
                         "strength": "Checks the flagged pattern is gone. Does not check behaviour."}}

    if deps.llm.enabled:
        prompt = (
            f"Write ONE pytest file that fails on the original code and passes on the patched code.\n"
            f"Finding: {finding['title']} at {path}:{finding['line']}\nPatch explanation: {proposal['explanation']}\n"
            f"Repository files are at /work/repo/<path> and already on sys.path, so import modules directly.\n"
            "Do not import os, sys, subprocess, socket, pathlib, shutil or network libraries. Do not use open() or exec().\n"
            f"<untrusted_code>\n{redact(window(original, finding['line'], 35))}\n</untrusted_code>\n"
            'Return JSON {"test_code":"..."}.'
        )
        try:
            result = await deps.llm.complete_json(prompt, max_tokens=1500)
            code = str(result.get("test_code", ""))
            problem = screen_test_code(code)
            if problem is None:
                deps.emit("generate_tests", "done", "Model wrote a regression test (will run in the sandbox).", "llm")
                return {"test": {"path": TEST_PATH, "code": code, "kind": "behaviour", "source": "llm",
                                 "strength": "Model-written; only meaningful if it fails before and passes after."}}
            deps.emit("generate_tests", "running", f"Rejected model test ({problem}); using a syntax check instead.")
        except LLMError as exc:
            deps.emit("generate_tests", "running", f"Model unavailable ({exc}); using a syntax check instead.")

    deps.emit("generate_tests", "done", "Generated a syntax-validity test (weak evidence).", "rule")
    return {"test": {"path": TEST_PATH, "code": _SYNTAX.format(path=path), "kind": "syntax", "source": "template",
                     "strength": "Only proves the patched file parses."}}
